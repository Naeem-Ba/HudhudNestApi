using MediatR;
using HudhudNestApi.Application.Common.Exceptions;
using HudhudNestApi.Domain.Listings.Enums;

namespace HudhudNestApi.Application.Listings.Views;

/// <summary>
/// "Someone opened this listing's detail page." Everything the client could lie about is derived
/// on the server: the listing id comes from the route, identity from the token/visitor header, and
/// the total is never an input.
/// </summary>
/// <param name="VisitorToken">Opaque random id the browser/app keeps for anonymous visitors; null if absent.</param>
/// <param name="Fingerprint">Server-derived fallback (IP + user agent) used only when there is neither a user nor a visitor token.</param>
/// <param name="IsAutomated">Known crawler / headless client according to the user agent.</param>
/// <param name="IsTestTraffic">Request carried the configured test-traffic secret (E2E, smoke tests).</param>
public sealed record RecordListingViewCommand(
    ListingKind Kind,
    Guid ListingId,
    Guid? UserId,
    bool IsAdmin,
    string? VisitorToken,
    string? Fingerprint,
    bool IsAutomated,
    bool IsTestTraffic) : IRequest<ListingViewResultDto>;

public sealed class RecordListingViewCommandHandler : IRequestHandler<RecordListingViewCommand, ListingViewResultDto>
{
    private readonly IListingViewRepository _views;
    private readonly IListingViewPolicy _policy;

    public RecordListingViewCommandHandler(IListingViewRepository views, IListingViewPolicy policy)
    {
        _views = views;
        _policy = policy;
    }

    public async Task<ListingViewResultDto> Handle(RecordListingViewCommand request, CancellationToken ct)
    {
        // An unknown, deleted, unpublished or expired listing is a 404 for everyone, bots included:
        // the counter must not confirm that a hidden listing exists.
        var target = await _views.GetTargetAsync(request.Kind, request.ListingId, ct);
        if (target is null || !target.IsPubliclyViewable)
            throw new NotFoundException("Listing was not found.");

        if (request.IsTestTraffic)
            return await NotCountedAsync(request, "test-traffic", ct);

        if (request.IsAutomated)
            return await NotCountedAsync(request, "automated", ct);

        if (request.UserId is { } userId && await IsOwnTrafficAsync(request, userId, target, ct))
            return await NotCountedAsync(request, "own-listing", ct);

        var identity = ResolveIdentity(request);
        var now = DateTime.UtcNow;
        var (counted, total) = await _views.TryRecordAsync(
            request.Kind, request.ListingId, _policy.HashViewer(identity), _policy.BucketFor(now), now, ct);

        return new ListingViewResultDto(counted, total, counted ? null : "cooldown");
    }

    private async Task<ListingViewResultDto> NotCountedAsync(RecordListingViewCommand request, string reason, CancellationToken ct)
    {
        var counts = await _views.GetCountsAsync(request.Kind, new[] { request.ListingId }, ct);
        return new ListingViewResultDto(false, counts.TryGetValue(request.ListingId, out var n) ? n : 0, reason);
    }

    private async Task<bool> IsOwnTrafficAsync(
        RecordListingViewCommand request, Guid userId, ListingViewTarget target, CancellationToken ct)
    {
        // Admin previews, the owner, and anyone working for the agency the listing is published under
        // are not an audience.
        if (request.IsAdmin || target.OwnerId == userId)
            return true;

        if (target.AgencyId is { } agencyId)
            return await _views.GetUserAgencyIdAsync(userId, ct) == agencyId;

        return false;
    }

    private static string ResolveIdentity(RecordListingViewCommand request)
    {
        if (request.UserId is { } userId)
            return $"u:{userId:N}";

        if (IsValidVisitorToken(request.VisitorToken))
            return $"v:{request.VisitorToken}";

        // No account and no token (scripts, very old clients): fall back to a coarse server-side
        // fingerprint. It under-counts people sharing a network, which is the safe direction.
        return $"f:{request.Fingerprint ?? "unknown"}";
    }

    /// <summary>Visitor tokens are random ids generated by our clients: 16-64 chars of [A-Za-z0-9-].</summary>
    public static bool IsValidVisitorToken(string? token)
    {
        if (token is null || token.Length < 16 || token.Length > 64)
            return false;

        foreach (var c in token)
        {
            if (!(char.IsAsciiLetterOrDigit(c) || c == '-'))
                return false;
        }

        return true;
    }
}
