namespace PropertyApi.Domain.Listings.Enums;

/// <summary>
/// وحدة قياس المساحة كما أدخلها المستخدم. القيمة المخزَّنة في Property.Area هي
/// دائماً "كما أدخلها المستخدم بهذه الوحدة" — لا يوجد تحويل تلقائي إلى متر مربع.
///
/// لماذا لا يوجد تحويل تلقائي للقصبة؟ قيمة القصبة تختلف فعلياً بين مناطق سوريا
/// (لا معيار عالمي موحّد وموثَّق)، فأي تحويل ثابت هنا سيكون خاطئاً لبعض
/// المستخدمين. إن احتاج النظام لاحقاً إلى مساحة موحّدة للبحث/الفرز، يُضاف حقل
/// منفصل (مثلاً NormalizedAreaM2) محسوباً وفق معيار موثّق ومحدَّد — وليس هنا.
/// </summary>
public enum AreaUnit
{
    /// <summary>متر مربع — الوحدة الافتراضية والأكثر شيوعاً للعقارات السكنية/التجارية.</summary>
    SquareMeter,

    /// <summary>قصبة — وحدة محلية شائعة، قيمتها تختلف بين المناطق.</summary>
    Qasabah,

    /// <summary>دونم — شائعة للأراضي الزراعية.</summary>
    Dunum,

    /// <summary>هكتار — للمساحات الزراعية/الصناعية الكبيرة.</summary>
    Hectare
}
